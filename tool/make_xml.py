#!/usr/bin/env python
"""Writes the 1%-step battery level-lists for the Motorola XT550 (Android 2.3).

The stock icons have one picture per 5 %. These level-lists keep the stock
artwork but show the exact number:

- stat_sys_battery.xml (not charging): 101 items, one per level 0..100. Each
  is a layer-list with
  - the stock battery body nearest to the level, in 10 % steps
    (stat_sys_battery_0, _10, ..., _100; 1-2 % keep the empty body, 3-14 % the
    10 % body);
  - the number, one bitmap per digit (digits live in the _5, _15, ..., _95
    slots, see MakeDigits.java), each placed with insets and gravity top|left
    so it is not stretched.
- stat_sys_battery_charge.xml and stat_sys_battery_charge_1.xml (charging):
  101 items. Each is a layer-list of the stock charging animation (the same
  frames and timings that stat_sys_battery_charge.xml used for that level) with
  the number on top.

usage: make_xml.py <res dir> <prefix>
       <prefix> is "@*android:drawable/" to compile against framework-res, or
       "@drawable/" for the on-phone render test app.
"""
import pathlib
import sys

GLYPH_W = {d: (3 if d == 1 else 5) for d in range(10)}
BODY_X0, BODY_W, TEXT_Y = 2, 19, 8  # battery body x 2..20; text rows 8..16
ANDROID = 'xmlns:android="http://schemas.android.com/apk/res/android"'
# Stock stat_sys_battery_charge.xml: (max level, first frame); then frames run to 5.
CHARGE_GROUPS = [(14, 0), (29, 1), (49, 2), (69, 3), (89, 4), (101, 5)]


def digits_layers(level, p):
    ds = [int(c) for c in str(level)]
    width = sum(GLYPH_W[d] for d in ds) + len(ds) - 1
    x = BODY_X0 + (BODY_W - width) // 2
    out = []
    for d in ds:
        out.append(
            '<item android:left="%dpx" android:top="%dpx">'
            '<bitmap android:src="%sstat_sys_battery_%d" android:gravity="top|left" /></item>'
            % (x - 1, TEXT_Y - 1, p, 10 * d + 5))
        x += GLYPH_W[d] + 1
    return out


def body(level):
    if level <= 2:
        return 0
    return max(10, min(100, (level + 5) // 10 * 10))


def charge_anim(level, p):
    first = next(f for top, f in CHARGE_GROUPS if level <= top)
    frames = ['<item android:drawable="%sstat_sys_battery_charge_anim%d" android:duration="%d" />'
              % (p, f, 2000 if f == first else 1000) for f in range(first, 6)]
    return '<item><animation-list android:oneshot="false">%s</animation-list></item>' % ''.join(frames)


def level_list(p, charging):
    items = []
    for level in range(101):
        top = 101 if (charging and level == 100) else level
        base = (charge_anim(level, p) if charging
                else '<item android:drawable="%sstat_sys_battery_%d" />' % (p, body(level)))
        items.append('  <item android:maxLevel="%d"><layer-list>%s%s</layer-list></item>'
                     % (top, base, ''.join(digits_layers(level, p))))
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            '<!-- Generated by make_xml.py: battery icon with the exact percentage. -->\n'
            '<level-list %s>\n%s\n</level-list>\n' % (ANDROID, '\n'.join(items)))


def main():
    res, prefix = pathlib.Path(sys.argv[1]), sys.argv[2]
    d = res / 'drawable'
    d.mkdir(parents=True, exist_ok=True)
    (d / 'stat_sys_battery.xml').write_text(level_list(prefix, False), newline='\n')
    for name in ('stat_sys_battery_charge.xml', 'stat_sys_battery_charge_1.xml'):
        (d / name).write_text(level_list(prefix, True), newline='\n')
    print('written to', d)


if __name__ == '__main__':
    main()
